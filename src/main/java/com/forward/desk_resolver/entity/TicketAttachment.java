package com.forward.desk_resolver.entity;

import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.FetchType;
import jakarta.persistence.GeneratedValue;
import jakarta.persistence.GenerationType;
import jakarta.persistence.Id;
import jakarta.persistence.JoinColumn;
import jakarta.persistence.ManyToOne;
import jakarta.persistence.Table;
import lombok.Getter;
import lombok.Setter;

import java.time.Instant;

/**
 * The record of one file attached to a ticket. The bytes are not here.
 *
 * <p><strong>The row and the blob are two separate things, stored in two places.</strong> The file
 * lives on disk under {@code app.storage.attachments.directory} and this row names it. The alternative
 * - a {@code bytea} column - was not chosen: it would put arbitrary user-supplied megabytes through
 * the connection pool and into every backup of a database whose other tables are small enough to dump
 * in seconds, and it would make a streaming download a question of how much heap one request may use.
 *
 * <p>The cost of that split is honest and worth stating: the two can disagree. A row whose file is
 * gone is possible, and {@code TicketAttachmentServiceImpl} handles it explicitly rather than
 * discovering it as a stack trace. Nothing in a single transaction covers both a database insert and a
 * filesystem write.
 *
 * <p><strong>{@link #fileName} and {@link #filePath} are not variations on one idea</strong>, and
 * confusing them is the vulnerability this class is shaped to avoid:
 *
 * <ul>
 *   <li>{@link #fileName} is what the client called it. It is attacker-controlled, may contain
 *       {@code ../} or a drive letter or a null byte, and is used for exactly two things: showing in a
 *       list, and the {@code Content-Disposition} header on a download. Never for building a path.
 *   <li>{@link #filePath} is generated by this application - {@code <ticketId>/<uuid><ext>} - and is
 *       the only thing the storage layer will resolve. A client cannot influence it, so a client
 *       cannot steer a read or a write anywhere.
 * </ul>
 *
 * <p>Append-only, like {@link TicketComment}: no update or delete endpoint exists, so there is no
 * {@code @Version} and no way to orphan a blob by rewriting the row that points at it.
 */
@Entity
@Table(name = "ticket_attachments")
@Getter
@Setter
public class TicketAttachment {

    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    private Long id;

    /** The client's name for the file. Display and download only; see the class comment. */
    @Column(name = "file_name", nullable = false, length = 255)
    private String fileName;

    /**
     * Storage key relative to the configured attachment directory, generated by this application.
     *
     * <p>Unique since {@code V19}: one row per blob, so a generation collision is a failed insert
     * rather than two rows quietly sharing a file.
     */
    @Column(name = "file_path", nullable = false, unique = true, length = 500)
    private String filePath;

    /**
     * The content type this upload was accepted as.
     *
     * <p>Nullable because {@code V5} made it so, but in practice never null for a row this application
     * wrote: an upload with no usable content type is refused before it reaches here, because the
     * allow-list has nothing to match it against.
     */
    @Column(name = "file_type", length = 100)
    private String fileType;

    /** Byte count as written. Stored rather than read back off disk - see {@code V19}. */
    @Column(name = "size_bytes", nullable = false)
    private Long sizeBytes;

    @Column(name = "uploaded_at", nullable = false)
    private Instant uploadedAt;

    @ManyToOne(fetch = FetchType.LAZY)
    @JoinColumn(name = "ticket_id", nullable = false)
    private Ticket ticket;

    /** Who uploaded it, from the access token. Added by {@code V19}; see that migration for why. */
    @ManyToOne(fetch = FetchType.LAZY)
    @JoinColumn(name = "uploaded_by", nullable = false)
    private User uploadedBy;
}
